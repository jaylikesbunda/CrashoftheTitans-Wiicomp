"""Emit one LLVM IR module for a set of generated nWii guest functions.

Reuses the semantic C++ grammar (lift_guest_cpp) and emits whole-module IR:

  * guest GPRs / CR / XER / LR / inst_count live in `alloca`s promoted to SSA by
    mem2reg, so a real host register allocator sees the guest register file.
  * the MMU is an `alwaysinline` mask + range-check + `llvm.bswap` fast path with
    a cold call to the same runtime slow path the C++ header calls.
  * `ctx` is an opaque `ptr`, used only for the MMU and opaque callees.

Two ABIs:
  --abi spec  a lifted callee gets a register-by-value signature with its dirty
              registers returned and `alwaysinline`; the caller keeps guest state
              in SSA across the call (no per-call ctx round-trip).
  --abi full  the current C++ shape: `void f(ptr ctx)`, all state through ctx.

usage:
  python emit_llvm_module.py --gen DIR --module module.json --offsets off.json \
      --abi spec -o module.ll
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import lift_guest_cpp as L  # noqa: E402

MEM1_LIMIT = 24 * 1024 * 1024
MEM2_LIMIT = 64 * 1024 * 1024
MEM2_BASE = 0x10000000
GX_PIPE_PAGE = 0x0C008000
CRBIT = {'lt': 0, 'gt': 1, 'eq': 2, 'so': 3}


def extract_sources(gen: Path) -> dict:
    srcs = {}
    for f in sorted(gen.glob('output_*.cpp')):
        t = f.read_text(errors='replace')
        pos = [(m.start(), m.group(1)) for m in re.finditer(
            r'^void (func_([0-9A-F]{8}))\(NWII_CTX_PARAM ctx\) \{', t, re.M)]
        for i, (s, name) in enumerate(pos):
            e = pos[i + 1][0] if i + 1 < len(pos) else len(t)
            srcs[name] = t[s:e]
    return srcs


def prepare(fns):
    """Topologically annotate each lifted function with interprocedural in/def sets."""
    order = []
    seen = set()

    def visit(n):
        if n in seen:
            return
        seen.add(n)
        for c in fns[n].calls:
            visit(c)
        order.append(n)
    for n in fns:
        visit(n)
    for n in order:
        fn = fns[n]
        ins = set(fn.inputs)
        defs = set(fn.defs)
        crs = set(fn.cr_in) | set(fn.cr_out)
        xu = bool(fn.xer_in or fn.xer_out)
        for c in fn.calls:
            cf = fns[c]
            ins |= cf.ins
            defs |= cf.defs_all
            crs |= cf.crs
            xu = xu or cf.xer_used
        fn.ins = ins
        fn.defs_all = defs
        fn.args_set = ins | defs
        fn.need = set(ins) | (defs - set(fn.mustdef))
        fn.crs = crs
        fn.xer_used = xu
    return order


# ---------------------------------------------------------------------------
class Emitter:
    def __init__(self, fns, off, abi):
        self.fns = fns
        self.off = off
        self.abi = abi
        self.buf = []
        self.n = 0

    def f(self, tag):
        self.n += 1
        return '%' + tag + str(self.n)

    def e(self, t):
        self.buf.append('  ' + t)

    def lab(self, t):
        self.buf.append((t[1:] if t.startswith('%') else t) + ':')

    # ---- module --------------------------------------------------------
    def header(self):
        b = self.buf
        b.append('; nWii whole-module LLVM IR (%s ABI), generated by emit_llvm_module.py' % self.abi)
        b.append('target triple = "x86_64-w64-windows-gnu"')
        b.append('')
        b.append('declare i32 @llvm.bswap.i32(i32)')
        b.append('declare i16 @llvm.bswap.i16(i16)')
        b.append('declare i32 @llvm.fshl.i32(i32, i32, i32)')
        b.append('declare void @nwii_interpret_step(ptr)')
        b.append('declare i8  @nwii_read8_slow(ptr, i32)')
        b.append('declare i16 @nwii_read16_slow(ptr, i32)')
        b.append('declare i32 @nwii_read32_slow(ptr, i32)')
        b.append('declare void @nwii_write8_slow(ptr, i32, i32)')
        b.append('declare void @nwii_write16_slow(ptr, i32, i32)')
        b.append('declare void @nwii_write32_slow(ptr, i32, i32)')
        b.append('declare void @nwii_gx_wgpipe_write8(i32)')
        b.append('declare void @nwii_gx_wgpipe_write16(i32)')
        b.append('declare void @nwii_gx_wgpipe_write32(i32)')
        b.append('@_ZN4nwii7runtime12g_watch_addrE = external global i32')
        b.append('')

    def mmu(self):
        b = self.buf
        o = self.off
        for w in (8, 16, 32):
            ty = 'i%d' % w if w < 32 else 'i32'
            b.append('define internal ' + ty + ' @nwii_read' + str(w) + '(ptr %ctx, i32 %addr) alwaysinline {')
            b += ['entry:',
                  '  %paddr = and i32 %addr, 1073741823',
                  '  %in1 = icmp ult i32 %paddr, ' + str(MEM1_LIMIT),
                  '  br i1 %in1, label %m1, label %chk2',
                  'm1:']
            if w == 32:
                b += ['  %is12 = icmp eq i32 %paddr, 12',
                      '  br i1 %is12, label %ret0, label %m1do',
                      'm1do:']
            b += ['  %g1 = getelementptr i8, ptr %ctx, i64 ' + str(o['mem1_base']),
                  '  %base1 = load ptr, ptr %g1, align 8',
                  '  %idx1 = zext i32 %paddr to i64',
                  '  %p1 = getelementptr i8, ptr %base1, i64 %idx1',
                  '  %v1 = load ' + ty + ', ptr %p1, align 1']
            b.append('  %s1 = ' + ('call ' + ty + ' @llvm.bswap.i' + str(w) + '(' + ty + ' %v1)'
                                   if w > 8 else 'add i8 %v1, 0'))
            b.append('  ret ' + ty + ' %s1')
            if w == 32:
                b += ['ret0:', '  ret i32 0']
            b += ['chk2:',
                  '  %off2 = sub i32 %paddr, ' + str(MEM2_BASE),
                  '  %in2 = icmp ult i32 %off2, ' + str(MEM2_LIMIT),
                  '  br i1 %in2, label %m2do, label %slow',
                  'm2do:',
                  '  %g2 = getelementptr i8, ptr %ctx, i64 ' + str(o['mem2_base']),
                  '  %base2 = load ptr, ptr %g2, align 8',
                  '  %idx2 = zext i32 %off2 to i64',
                  '  %p2 = getelementptr i8, ptr %base2, i64 %idx2',
                  '  %v2 = load ' + ty + ', ptr %p2, align 1']
            b.append('  %s2 = ' + ('call ' + ty + ' @llvm.bswap.i' + str(w) + '(' + ty + ' %v2)'
                                   if w > 8 else 'add i8 %v2, 0'))
            b += ['  ret ' + ty + ' %s2',
                  'slow:',
                  '  %sv = call ' + ty + ' @nwii_read' + str(w) + '_slow(ptr %ctx, i32 %addr)',
                  '  ret ' + ty + ' %sv',
                  '}',
                  '']
        for w in (8, 16, 32):
            ty = 'i%d' % w if w < 32 else 'i32'
            nb = {8: 1, 16: 2, 32: 4}[w]
            b.append('define internal void @nwii_write' + str(w) + '(ptr %ctx, i32 %addr, ' + ty + ' %value) alwaysinline {')
            b += ['entry:',
                  '  %paddr = and i32 %addr, 1073741823',
                  '  %sub = sub i32 %paddr, 65536',
                  '  %in1 = icmp ult i32 %sub, ' + str(MEM1_LIMIT - 65536),
                  '  br i1 %in1, label %m1, label %chk2',
                  'm1:',
                  '  %gw1 = load i32, ptr @_ZN4nwii7runtime12g_watch_addrE, align 4',
                  '  %gwa = and i32 %gw1, 1073741823',
                  '  %gwp = lshr i32 %gwa, 16',
                  '  %pp = lshr i32 %paddr, 16',
                  '  %wp = icmp eq i32 %pp, %gwp',
                  '  br i1 %wp, label %slow, label %m1do',
                  'm1do:',
                  '  %g1 = getelementptr i8, ptr %ctx, i64 ' + str(o['mem1_base']),
                  '  %base1 = load ptr, ptr %g1, align 8',
                  '  %idx1 = zext i32 %paddr to i64',
                  '  %p1 = getelementptr i8, ptr %base1, i64 %idx1']
            b.append('  %b1 = ' + ('call ' + ty + ' @llvm.bswap.i' + str(w) + '(' + ty + ' %value)'
                                   if w > 8 else 'add i8 %value, 0'))
            b += ['  store ' + ty + ' %b1, ptr %p1, align 1',
                  '  ret void',
                  'chk2:',
                  '  %off2 = sub i32 %paddr, ' + str(MEM2_BASE),
                  '  %in2 = icmp ult i32 %off2, ' + str(MEM2_LIMIT),
                  '  br i1 %in2, label %m2do, label %chk3',
                  'm2do:',
                  '  %g2 = getelementptr i8, ptr %ctx, i64 ' + str(o['mem2_base']),
                  '  %base2 = load ptr, ptr %g2, align 8',
                  '  %idx2 = zext i32 %off2 to i64',
                  '  %p2 = getelementptr i8, ptr %base2, i64 %idx2']
            b.append('  %b2 = ' + ('call ' + ty + ' @llvm.bswap.i' + str(w) + '(' + ty + ' %value)'
                                   if w > 8 else 'add i8 %value, 0'))
            b += ['  store ' + ty + ' %b2, ptr %p2, align 1',
                  '  ret void',
                  'chk3:',
                  '  %pg = and i32 %paddr, 4294963200',
                  '  %iswg = icmp eq i32 %pg, ' + str(GX_PIPE_PAGE),
                  '  br i1 %iswg, label %wg, label %slow',
                  'wg:',
                  '  %gw3 = load i32, ptr @_ZN4nwii7runtime12g_watch_addrE, align 4',
                  '  %wnz = icmp ne i32 %gw3, 0',
                  '  %wm = and i32 %gw3, 1073741816',
                  '  %wd = add i32 %paddr, ' + str(nb - 1),
                  '  %wd2 = sub i32 %wd, %wm',
                  '  %whit = icmp ult i32 %wd2, ' + str(nb + 7),
                  '  %wmay = and i1 %wnz, %whit',
                  '  br i1 %wmay, label %slow, label %wgdo',
                  'wgdo:',
                  ('  %val32 = add i32 %value, 0' if w == 32 else '  %val32 = zext ' + ty + ' %value to i32'),
                  '  call void @nwii_gx_wgpipe_write' + str(w) + '(i32 %val32)',
                  '  ret void',
                  'slow:',
                  ('  %vs = add i32 %value, 0' if w == 32 else '  %vs = zext ' + ty + ' %value to i32'),
                  '  call void @nwii_write' + str(w) + '_slow(ptr %ctx, i32 %addr, i32 %vs)',
                  '  ret void',
                  '}',
                  '']

    # ---- function body -------------------------------------------------
    def emit(self, order):
        b = self.buf
        for n in order:
            fn = self.fns[n]
            rett = ['i32'] * (len(fn.defs_all) + len(fn.crs) + (1 if fn.xer_used else 0) + 1) + ['i64', 'i32']
            b.append('%%R%s = type { %s }' % (n[5:], ', '.join(rett)))
        b.append('')
        for n in order:
            self.function(self.fns[n])
        for n in order:
            self.wrapper(self.fns[n])

    def _params(self, fn):
        if self.abi == 'spec':
            p = ['ptr %ctx'] + ['i32 %%in%d' % g for g in sorted(fn.need)]
            p += ['i32 %%cr%d' % f for f in sorted(fn.crs)]
            if fn.xer_used:
                p += ['i32 %xer']
            p += ['i32 %lr', 'i64 %ic']
        else:
            p = ['ptr %ctx']
        return p

    def function(self, fn):
        abi = self.abi
        b = self.buf
        retty = '%%R%s' % fn.name[5:] if abi == 'spec' else 'void'
        b.append('define internal %s @g_%s(%s) alwaysinline nounwind {' % (retty, fn.name[5:], ', '.join(self._params(fn))))
        self.lab('entry')
        self.allregs = sorted(fn.args_set)
        self.need = sorted(fn.need)
        self.ins = sorted(fn.ins)
        self.crs = sorted(fn.crs)
        self.xer_used = bool(fn.xer_used)
        for g in self.allregs:
            self.e('%%a_g%d = alloca i32' % g)
        for f in self.crs:
            self.e('%%a_cr%d = alloca i32' % f)
        self.e('%a_xer = alloca i32')
        self.e('%a_lr = alloca i32')
        self.e('%a_ic = alloca i64')
        self.e('%a_pc = alloca i32')
        if abi == 'spec':
            for g in self.need:
                self.e('store i32 %%in%d, ptr %%a_g%d' % (g, g))
            for f in self.crs:
                self.e('store i32 %%cr%d, ptr %%a_cr%d' % (f, f))
            if fn.xer_used:
                self.e('store i32 %xer, ptr %a_xer')
            self.e('store i32 %lr, ptr %a_lr')
            self.e('store i64 %ic, ptr %a_ic')
        else:
            for g in self.allregs:
                p = self.gep_ctx(self.off['gpr'] + 4 * g)
                v = self.ld(p, 'i32', 'gr')
                self.st('%%a_g%d' % g, 'i32', v)
            self._load_cr()
            if fn.xer_used:
                p = self.gep_ctx(self.off['xer']); self.st('%a_xer', 'i32', self.ld(p, 'i32', 'rx'))
            p = self.gep_ctx(self.off['lr']); self.st('%a_lr', 'i32', self.ld(p, 'i32', 'rl'))
            p = self.gep_ctx(self.off['inst_count']); self.st('%a_ic', 'i64', self.ld(p, 'i64', 'ri'))
        self.cur = 'entry'
        self.entry_pc = fn.entry
        self._body(fn)
        if self.cur is not None:
            self.e('br label %exit')
        self._exit(fn)
        b.append('}')
        b.append('')

    # helpers using explicit temporaries (readable IR; mem2reg cleans up)
    def gep_ctx(self, offset, tag='p'):
        n = self.f(tag)
        self.e('%s = getelementptr i8, ptr %%ctx, i64 %d' % (n, offset))
        return n

    def ld(self, ptr, ty, tag='l'):
        n = self.f(tag)
        self.e('%s = load %s, ptr %s' % (n, ty, ptr))
        return n

    def st(self, ptr, ty, val):
        self.e('store %s %s, ptr %s' % (ty, val, ptr))

    def gpr(self, g):
        return self.ld('%%a_g%d' % g, 'i32', 'lg')

    def setgpr(self, g, v):
        self.st('%%a_g%d' % g, 'i32', v)

    def ic_add(self, amount):
        cur = self.ld('%a_ic', 'i64', 'lic')
        n = self.f('ic')
        self.e('%s = add i64 %s, %d' % (n, cur, amount))
        self.st('%a_ic', 'i64', n)

    # ---- body / control flow ------------------------------------------
    def open(self, name):
        if self.cur is not None:
            self.e('br label %' + name)
        self.lab(name)
        self.cur = name

    def _body(self, fn):
        ops = fn.ops
        b = self.buf
        for i, op in enumerate(ops):
            k = op[0]
            if self.cur is None and k != 'label':
                continue  # unreachable filler after an unconditional terminator
            if k == 'label':
                self.open('L%08X' % op[1])
                continue
            if k == 'ic':
                self.ic_add(op[1]); continue
            if k in ('read', 'write'):
                _, r, a, off, w = op
                ea = self.f('ea')
                av = self.gpr(a)
                self.e('%s = add i32 %s, %d' % (ea, av, off))
                if k == 'read':
                    ty = 'i%d' % w if w < 32 else 'i32'
                    raw = self.f('rv')
                    self.e('%s = call %s @nwii_read%d(ptr %%ctx, i32 %s)' % (raw, ty, w, ea))
                    if w < 32:
                        n = self.f('ze'); self.e('%s = zext %s %s to i32' % (n, ty, raw))
                    else:
                        n = raw
                    self.setgpr(r, n)
                else:
                    sv = self.gpr(r)
                    if w < 32:
                        ty = 'i%d' % w
                        tv = self.f('tv'); self.e('%s = trunc i32 %s to %s' % (tv, sv, ty))
                        self.e('call void @nwii_write%d(ptr %%ctx, i32 %s, %s %s)' % (w, ea, ty, tv))
                    else:
                        self.e('call void @nwii_write%d(ptr %%ctx, i32 %s, i32 %s)' % (w, ea, sv))
                continue
            if self._alu(op):
                continue
            if k == 'setcr':
                self._setcr(op); continue
            if k == 'b':
                self.e('br label %%L%08X' % op[1]); self.cur = None; continue
            if k == 'bc':
                _, fld, bit, tgt, inv = op
                c = self._crcond(fld, bit, inv)
                ft = self.f('c')
                self.e('br i1 %s, label %%L%08X, label %s' % (c, tgt, ft))
                self.lab(ft)
                continue
            if k == 'bclr':
                _, fld, bit, inv = op
                c = self._crcond(fld, bit, inv)
                ret = self.f('ret')
                cont = self.f('k')
                self.e('br i1 %s, label %s, label %s' % (c, ret, cont))
                self.lab(ret)
                lv = self.ld('%a_lr', 'i32', 'lr')
                self.st('%a_pc', 'i32', lv)
                self.e('br label %exit')
                self.lab(cont)
                continue
            if k == 'blr':
                lv = self.ld('%a_lr', 'i32', 'lr')
                self.st('%a_pc', 'i32', lv)
                self.e('br label %exit'); self.cur = None; continue
            if k == 'retpc':
                self.st('%a_pc', 'i32', str(op[1]))
                self.e('br label %exit'); self.cur = None; continue
            if k == 'bl':
                self._call(op); continue
            raise SystemExit('emit: unhandled op %r' % (op,))

    def _call(self, op):
        _, target, ret, callee = op
        cf = self.fns[callee]
        if self.abi == 'spec':
            args = ['ptr %ctx']
            for g in sorted(cf.need):
                args.append('i32 ' + self.ld('%%a_g%d' % g, 'i32', 'cg'))
            for f in sorted(cf.crs):
                args.append('i32 ' + self.ld('%%a_cr%d' % f, 'i32', 'cc'))
            if cf.xer_used:
                args.append('i32 ' + self.ld('%a_xer', 'i32', 'cx'))
            args.append('i32 ' + str(ret))
            args.append('i64 ' + self.ld('%a_ic', 'i64', 'ci'))
            r = self.f('cr')
            self.e('%s = call %%R%s @g_%s(%s)' % (r, callee[5:], callee[5:], ', '.join(args)))
            base = len(cf.defs_all)
            for i, d in enumerate(cf.defs_all):
                e = self.f('e'); self.e('%s = extractvalue %%R%s %s, %d' % (e, callee[5:], r, i))
                self.st('%%a_g%d' % d, 'i32', e)
            for i, f in enumerate(sorted(cf.crs)):
                e = self.f('e'); self.e('%s = extractvalue %%R%s %s, %d' % (e, callee[5:], r, base + i))
                self.st('%%a_cr%d' % f, 'i32', e)
            ci = base + len(cf.crs)
            if cf.xer_used:
                e = self.f('e'); self.e('%s = extractvalue %%R%s %s, %d' % (e, callee[5:], r, ci))
                self.st('%a_xer', 'i32', e); ci += 1
            e = self.f('e'); self.e('%s = extractvalue %%R%s %s, %d' % (e, callee[5:], r, ci))
            self.st('%a_lr', 'i32', e); ci += 1
            e = self.f('e'); self.e('%s = extractvalue %%R%s %s, %d' % (e, callee[5:], r, ci))
            self.st('%a_ic', 'i64', e); ci += 1
            e = self.f('e'); self.e('%s = extractvalue %%R%s %s, %d' % (e, callee[5:], r, ci))
            self.st('%a_pc', 'i32', e)
            ok = self.f('ok'); self.e('%s = icmp eq i32 %s, %d' % (ok, e, ret))
            cont = self.f('ct'); prop = self.f('pp')
            self.e('br i1 %s, label %s, label %s' % (ok, cont, prop))
            self.lab(prop)
            self.e('br label %exit')
            self.lab(cont)
        else:
            self._materialize_all()
            p = self.gep_ctx(self.off['lr']); self.st(p, 'i32', str(ret))
            p = self.gep_ctx(self.off['pc']); self.st(p, 'i32', str(target))
            self.e('call void @g_%s(ptr %%ctx)' % callee[5:])
            self._reload_all()
            p = self.gep_ctx(self.off['pc']); pv = self.ld(p, 'i32', 'pc')
            ok = self.f('ok'); self.e('%s = icmp eq i32 %s, %d' % (ok, pv, ret))
            cont = self.f('ct'); prop = self.f('pp')
            self.e('br i1 %s, label %s, label %s' % (ok, cont, prop))
            self.lab(prop)
            self.e('br label %exit')
            self.lab(cont)

    def _materialize_all(self):
        for g in self.allregs:
            p = self.gep_ctx(self.off['gpr'] + 4 * g)
            self.st(p, 'i32', self.ld('%%a_g%d' % g, 'i32', 'mg'))
        self._store_cr()
        p = self.gep_ctx(self.off['xer'])
        if self.xer_used:
            self.st(p, 'i32', self.ld('%a_xer', 'i32', 'mx'))
        p = self.gep_ctx(self.off['lr']); self.st(p, 'i32', self.ld('%a_lr', 'i32', 'ml'))
        p = self.gep_ctx(self.off['inst_count']); self.st(p, 'i64', self.ld('%a_ic', 'i64', 'mi'))

    def _reload_all(self):
        for g in self.allregs:
            p = self.gep_ctx(self.off['gpr'] + 4 * g)
            self.st('%%a_g%d' % g, 'i32', self.ld(p, 'i32', 'rg'))
        self._load_cr()
        p = self.gep_ctx(self.off['xer'])
        if self.xer_used:
            self.st('%a_xer', 'i32', self.ld(p, 'i32', 'rx'))
        p = self.gep_ctx(self.off['lr']); self.st('%a_lr', 'i32', self.ld(p, 'i32', 'rl'))
        p = self.gep_ctx(self.off['inst_count']); self.st('%a_ic', 'i64', self.ld(p, 'i64', 'ri'))

    def _load_cr(self):
        for f in self.crs:
            acc = None
            for idx in range(4):
                p = self.gep_ctx(self.off['cr'] + 4 * f + idx, 'cp')
                by = self.ld(p, 'i8', 'cb')
                z = self.f('z'); self.e('%s = zext i8 %s to i32' % (z, by))
                if idx:
                    s = self.f('sh'); self.e('%s = shl i32 %s, %d' % (s, z, idx)); z = s
                if acc is None:
                    acc = z
                else:
                    o = self.f('or'); self.e('%s = or i32 %s, %s' % (o, acc, z)); acc = o
            self.st('%%a_cr%d' % f, 'i32', acc)

    def _fall(self, tag):
        n = self.f(tag)
        self.lab(n)
        return n

    def _alu(self, op):
        k = op[0]
        if k in ('mr', 'mflr', 'extsh', 'li', 'addi', 'add', 'subf', 'mullw',
                 'mulli', 'mulhwu', 'divwu', 'or', 'orc', 'ori', 'rlwinm', 'srawi', 'mtlr'):
            pass
        else:
            return False
        if k == 'mr':
            self.setgpr(op[1], self.gpr(op[2]))
        elif k == 'mflr':
            self.setgpr(op[1], self.ld('%a_lr', 'i32', 'mflr'))
        elif k == 'mtlr':
            self.st('%a_lr', 'i32', self.gpr(op[1]))
        elif k == 'extsh':
            a = self.gpr(op[2]); t = self.f('t16'); s = self.f('se')
            self.e('%s = trunc i32 %s to i16' % (t, a))
            self.e('%s = sext i16 %s to i32' % (s, t))
            self.setgpr(op[1], s)
        elif k == 'li':
            self.setgpr(op[1], str(op[2]))
        elif k == 'addi':
            v = self.f('ad'); self.e('%s = add i32 %s, %d' % (v, self.gpr(op[2]), _s32(op[3]))); self.setgpr(op[1], v)
        elif k == 'add':
            v = self.f('ad'); self.e('%s = add i32 %s, %s' % (v, self.gpr(op[2]), self.gpr(op[3]))); self.setgpr(op[1], v)
        elif k == 'subf':
            v = self.f('sb'); self.e('%s = sub i32 %s, %s' % (v, self.gpr(op[2]), self.gpr(op[3]))); self.setgpr(op[1], v)
        elif k == 'mullw':
            v = self.f('ml'); self.e('%s = mul i32 %s, %s' % (v, self.gpr(op[2]), self.gpr(op[3]))); self.setgpr(op[1], v)
        elif k == 'mulli':
            v = self.f('ml'); self.e('%s = mul i32 %s, %d' % (v, self.gpr(op[2]), _s32(op[3]))); self.setgpr(op[1], v)
        elif k == 'mulhwu':
            a = self.f('z'); c = self.f('z'); m = self.f('m'); h = self.f('h')
            self.e('%s = zext i32 %s to i64' % (a, self.gpr(op[2])))
            self.e('%s = zext i32 %s to i64' % (c, self.gpr(op[3])))
            self.e('%s = mul i64 %s, %s' % (m, a, c))
            self.e('%s = lshr i64 %s, 32' % (h, m))
            t = self.f('t'); self.e('%s = trunc i64 %s to i32' % (t, h)); self.setgpr(op[1], t)
        elif k == 'divwu':
            d = self.f('dn'); iz = self.f('iz'); dn = self.f('d2'); q = self.f('dv'); r = self.f('rs')
            self.e('%s = icmp eq i32 %s, 0' % (iz, self.gpr(op[3])))
            self.e('%s = select i1 %s, i32 1, i32 %s' % (dn, iz, self.gpr(op[3])))
            self.e('%s = udiv i32 %s, %s' % (q, self.gpr(op[2]), dn))
            self.e('%s = select i1 %s, i32 0, i32 %s' % (r, iz, q))
            self.setgpr(op[1], r)
        elif k == 'or' or k == 'orc':
            b = self.gpr(op[3])
            if k == 'orc':
                nb = self.f('nb'); self.e('%s = xor i32 %s, -1' % (nb, b)); b = nb
            v = self.f('or'); self.e('%s = or i32 %s, %s' % (v, self.gpr(op[2]), b)); self.setgpr(op[1], v)
        elif k == 'ori':
            v = self.f('or'); self.e('%s = or i32 %s, %d' % (v, self.gpr(op[2]), op[3])); self.setgpr(op[1], v)
        elif k == 'rlwinm':
            v = self.f('rl'); m = self.f('an')
            self.e('%s = call i32 @llvm.fshl.i32(i32 %s, i32 %s, i32 %d)' % (v, self.gpr(op[2]), self.gpr(op[2]), op[3]))
            self.e('%s = and i32 %s, %d' % (m, v, op[4]))
            self.setgpr(op[1], m)
        elif k == 'srawi':
            _, d, a, sh, mask, xb = op
            av = self.gpr(a)
            sv = self.f('sv'); mv = self.f('mk'); neg = self.f('ng'); nz = self.f('nz'); ca = self.f('ca'); cz = self.f('cz')
            xv = self.ld('%a_xer', 'i32', 'xr'); cl = self.f('cl'); st = self.f('st'); nx = self.f('nx')
            self.e('%s = ashr i32 %s, %d' % (sv, av, sh))
            self.setgpr(d, sv)
            self.e('%s = and i32 %s, %d' % (mv, av, mask))
            self.e('%s = icmp slt i32 %s, 0' % (neg, av))
            self.e('%s = icmp ne i32 %s, 0' % (nz, mv))
            self.e('%s = and i1 %s, %s' % (ca, neg, nz))
            self.e('%s = zext i1 %s to i32' % (cz, ca))
            self.e('%s = and i32 %s, %d' % (cl, xv, ~(1 << xb) & 0xFFFFFFFF))
            self.e('%s = shl i32 %s, %d' % (st, cz, xb))
            self.e('%s = or i32 %s, %s' % (nx, cl, st))
            self.st('%a_xer', 'i32', nx)
        return True

    def _crbit_val(self, field, bit):
        v = self.ld('%%a_cr%d' % field, 'i32', 'cr')
        t = self.f('shr'); i = self.f('and')
        self.e('%s = lshr i32 %s, %d' % (t, v, CRBIT[bit]))
        self.e('%s = and i32 %s, 1' % (i, t))
        return i

    def _crcond(self, field, bit, invert):
        i = self._crbit_val(field, bit)
        c = self.f('cc')
        if invert:
            self.e('%s = icmp eq i32 %s, 0' % (c, i))
        else:
            self.e('%s = icmp ne i32 %s, 0' % (c, i))
        return c

    def _setcr(self, op):
        _, field, bit, spec = op
        if spec[0] == 'c':
            _, signed, ra, cop, kind, val = spec
            a = self.gpr(ra)
            if kind == 'imm':
                rhs = str(_s32(val)) if signed else str(val & 0xFFFFFFFF)
            else:
                rhs = self.gpr(val)
            t = self.f('cmp')
            if cop == '==':
                self.e('%s = icmp eq i32 %s, %s' % (t, a, rhs))
            elif signed:
                self.e('%s = icmp %s i32 %s, %s' % (t, 'slt' if cop == '<' else 'sgt', a, rhs))
            else:
                self.e('%s = icmp %s i32 %s, %s' % (t, 'ult' if cop == '<' else 'ugt', a, rhs))
        elif spec[0] == 'xer':
            _, sh, m = spec
            xv = self.ld('%a_xer', 'i32', 'xr')
            t1 = self.f('sh'); t2 = self.f('an'); t = self.f('ne')
            self.e('%s = lshr i32 %s, %d' % (t1, xv, sh))
            self.e('%s = and i32 %s, %d' % (t2, t1, m))
            self.e('%s = icmp ne i32 %s, 0' % (t, t2))
        else:  # xor -> always 0
            t = self.f('z'); self.e('%s = icmp eq i32 0, 0' % t)
        bit32 = self.f('bt'); self.e('%s = zext i1 %s to i32' % (bit32, t))
        old = self.ld('%%a_cr%d' % field, 'i32', 'oc')
        cl = self.f('cl'); sh = self.f('sh'); nv = self.f('nv')
        self.e('%s = and i32 %s, %d' % (cl, old, ~(1 << CRBIT[bit]) & 0xFFFFFFFF))
        self.e('%s = shl i32 %s, %d' % (sh, bit32, CRBIT[bit]))
        self.e('%s = or i32 %s, %s' % (nv, cl, sh))
        self.st('%%a_cr%d' % field, 'i32', nv)

    def _exit(self, fn):
        self.lab('exit')
        idx = {}
        cur = None
        struct = '%%R%s' % fn.name[5:]
        if self.abi == 'spec':
            cur = 'undef'
            for i, d in enumerate(fn.defs_all):
                v = self.ld('%%a_g%d' % d, 'i32', 'xd')
                n = self.f('iv')
                self.e('%s = insertvalue %s %s, i32 %s, %d' % (n, struct, cur, v, i))
                cur = n
            base = len(fn.defs_all)
            for i, f in enumerate(self.crs):
                v = self.ld('%%a_cr%d' % f, 'i32', 'xc')
                n = self.f('iv')
                self.e('%s = insertvalue %s %s, i32 %s, %d' % (n, struct, cur, v, base + i))
                cur = n
            ci = base + len(self.crs)
            if fn.xer_used:
                v = self.ld('%a_xer', 'i32', 'xs')
                n = self.f('iv')
                self.e('%s = insertvalue %s %s, i32 %s, %d' % (n, struct, cur, v, ci))
                cur = n; ci += 1
            v = self.ld('%a_lr', 'i32', 'xl')
            n = self.f('iv')
            self.e('%s = insertvalue %s %s, i32 %s, %d' % (n, struct, cur, v, ci))
            cur = n; ci += 1
            v = self.ld('%a_ic', 'i64', 'xi')
            n = self.f('iv')
            self.e('%s = insertvalue %s %s, i64 %s, %d' % (n, struct, cur, v, ci))
            cur = n; ci += 1
            v = self.ld('%a_pc', 'i32', 'xp')
            n = self.f('iv')
            self.e('%s = insertvalue %s %s, i32 %s, %d' % (n, struct, cur, v, ci))
            cur = n
            self.e('ret %s %s' % (struct, cur))
        else:
            self._store_state_to_ctx(fn)
            self.e('ret void')

    def _store_state_to_ctx(self, fn):
        for g in sorted(fn.defs_all):
            p = self.gep_ctx(self.off['gpr'] + 4 * g)
            self.st(p, 'i32', self.ld('%%a_g%d' % g, 'i32', 'sg'))
        self._store_cr()
        if self.xer_used:
            p = self.gep_ctx(self.off['xer']); self.st(p, 'i32', self.ld('%a_xer', 'i32', 'sx'))
        p = self.gep_ctx(self.off['lr']); self.st(p, 'i32', self.ld('%a_lr', 'i32', 'sl'))
        p = self.gep_ctx(self.off['inst_count']); self.st(p, 'i64', self.ld('%a_ic', 'i64', 'si'))
        p = self.gep_ctx(self.off['pc']); self.st(p, 'i32', self.ld('%a_pc', 'i32', 'sp'))

    def _store_cr(self):
        for f in self.crs:
            v = self.ld('%%a_cr%d' % f, 'i32', 'scr')
            for bit, idx in CRBIT.items():
                t = self.f('sh'); tr = self.f('tr'); an = self.f('an')
                self.e('%s = lshr i32 %s, %d' % (t, v, idx))
                self.e('%s = trunc i32 %s to i8' % (tr, t))
                self.e('%s = and i8 %s, 1' % (an, tr))
                p = self.gep_ctx(self.off['cr'] + 4 * f + idx)
                self.st(p, 'i8', an)

    # ---- external entry wrapper ---------------------------------------
    def wrapper(self, fn):
        b = self.buf
        b.append('define void @nwii_entry_%s(ptr %%ctx) alwaysinline nounwind {' % fn.name[5:])
        self.lab('entry')
        args = ['ptr %ctx']
        if self.abi == 'spec':
            for g in sorted(fn.need):
                p = self.gep_ctx(self.off['gpr'] + 4 * g, 'gp')
                v = self.ld(p, 'i32', 'gr')
                args.append('i32 ' + v)
        crmods = []
        for f in sorted(fn.crs):
            acc = None
            for idx in range(4):
                p = self.gep_ctx(self.off['cr'] + 4 * f + idx, 'cp')
                by = self.ld(p, 'i8', 'cb')
                z = self.f('z'); self.e('%s = zext i8 %s to i32' % (z, by))
                if idx:
                    s = self.f('sh'); self.e('%s = shl i32 %s, %d' % (s, z, idx)); z = s
                if acc is None:
                    acc = z
                else:
                    o = self.f('or'); self.e('%s = or i32 %s, %s' % (o, acc, z)); acc = o
            crmods.append(acc)
        p = self.gep_ctx(self.off['xer']); xv = self.ld(p, 'i32', 'xr') if fn.xer_used else None
        p = self.gep_ctx(self.off['lr']); lv = self.ld(p, 'i32', 'lr')
        p = self.gep_ctx(self.off['inst_count']); iv = self.ld(p, 'i64', 'ic')
        args += ['i32 ' + c for c in crmods]
        if fn.xer_used:
            args.append('i32 ' + xv)
        args += ['i32 ' + lv, 'i64 ' + iv]
        if self.abi == 'spec':
            r = self.f('rr')
            self.e('%s = call %%R%s @g_%s(%s)' % (r, fn.name[5:], fn.name[5:], ', '.join(args)))
            for i, d in enumerate(fn.defs_all):
                e = self.f('ev'); self.e('%s = extractvalue %%R%s %s, %d' % (e, fn.name[5:], r, i))
                p = self.gep_ctx(self.off['gpr'] + 4 * d, 'dp'); self.st(p, 'i32', e)
            base = len(fn.defs_all)
            for i, f in enumerate(sorted(fn.crs)):
                e = self.f('ev'); self.e('%s = extractvalue %%R%s %s, %d' % (e, fn.name[5:], r, base + i))
                self._spread_cr(f, e)
            ci = base + len(fn.crs)
            if fn.xer_used:
                e = self.f('ev'); self.e('%s = extractvalue %%R%s %s, %d' % (e, fn.name[5:], r, ci))
                p = self.gep_ctx(self.off['xer'], 'sp'); self.st(p, 'i32', e); ci += 1
            e = self.f('ev'); self.e('%s = extractvalue %%R%s %s, %d' % (e, fn.name[5:], r, ci))
            p = self.gep_ctx(self.off['lr'], 'sp'); self.st(p, 'i32', e); ci += 1
            e = self.f('ev'); self.e('%s = extractvalue %%R%s %s, %d' % (e, fn.name[5:], r, ci))
            p = self.gep_ctx(self.off['inst_count'], 'sp'); self.st(p, 'i64', e); ci += 1
            e = self.f('ev'); self.e('%s = extractvalue %%R%s %s, %d' % (e, fn.name[5:], r, ci))
            p = self.gep_ctx(self.off['pc'], 'sp'); self.st(p, 'i32', e)
        else:
            self.e('call void @g_%s(ptr %%ctx)' % fn.name[5:])
        b.append('  ret void')
        b.append('}')
        b.append('')

    def _spread_cr(self, f, v):
        for idx in range(4):
            t = self.f('sh'); tr = self.f('tr'); an = self.f('an')
            self.e('%s = lshr i32 %s, %d' % (t, v, idx))
            self.e('%s = trunc i32 %s to i8' % (tr, t))
            self.e('%s = and i8 %s, 1' % (an, tr))
            p = self.gep_ctx(self.off['cr'] + 4 * f + idx, 'cp')
            self.st(p, 'i8', an)


def _s32(v):
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v & 0x80000000 else v


def build(order, fns, off, abi):
    e = Emitter(fns, off, abi)
    e.header()
    e.mmu()
    e.emit(order)
    return '\n'.join(e.buf) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gen', required=True)
    ap.add_argument('--module', required=True)
    ap.add_argument('--offsets', required=True)
    ap.add_argument('--abi', choices=('spec', 'full'), default='spec')
    ap.add_argument('-o', '--out', required=True)
    a = ap.parse_args()
    gen = Path(a.gen)
    names = json.loads(Path(a.module).read_text())
    off = json.loads(Path(a.offsets).read_text())
    srcs = extract_sources(gen)
    fns = {}
    for n in names:
        if n not in srcs:
            raise SystemExit('missing source for ' + n)
        fns[n] = L.parse(n, srcs[n])
    order = prepare(fns)
    Path(a.out).write_text(build(order, fns, off, a.abi), encoding='utf-8')
    for n in order:
        print('%-14s ops=%3d ins=%s defs=%s calls=%s' % (
            n, len(fns[n].ops), sorted(fns[n].ins), sorted(fns[n].defs_all), fns[n].calls))
    print('wrote', a.out, 'functions', len(order))


if __name__ == '__main__':
    main()
