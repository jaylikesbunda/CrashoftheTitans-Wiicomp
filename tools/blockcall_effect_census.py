"""Price the promoted bounded-block sites (NATIVE_BOUNDED_BLOCKS_V1) and their static effect elision.

A qualified region's helper is generated by tools/block_codegen.py from the qualification record:
it loads exactly the record's `used` registers, runs the region's pure register body, stores
exactly the `dirty` registers, and threads ctx.inst_count through a local.  `block_codegen.eligible`
has already rejected every region containing a call, a label, an MMU access, a goto, `ctx` escape
or an unlisted field, so the helper cannot unwind and cannot touch anything but those registers.

That is the only reason the promoter spills the whole dirty set around a blockcall: an opaque
barrier must leave ctx authoritative in case something unwinds out of it.  For a blockcall the
exact read and write sets are known, so the site only needs

    spill(dirty & reads) ... native_block_F_A(ctx); ... reload(live & writes)

This tool promotes the hot set exactly as tools/fix_hot_split.py does and reports, per site and per
function, the register transfers the promoter emits now and the transfers the elision would keep.
Read-only: writes reports/blockcall-effects.json.
"""
from pathlib import Path
import argparse
import json
import re
import sys

PORT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PORT / 'tools'))
import barrier_census as C
import promote_regs as P

BLOCKCALL = re.compile(r'^\s*if\(native_blocks_on(?: && \(ctx\.msr&0x2000\))?\)\{(?P<body>.*?)'
                       r'native_block_(?P<function>[0-9A-F]{8})_(?P<address>[0-9A-F]{8})\(ctx\);'
                       r'(?P<tail>.*?)goto loc_(?P<target>[0-9A-F]{8});\}\s*$')
HELPER_HEAD = re.compile(r'^static inline void (native_block_([0-9A-F]{8})_([0-9A-F]{8}))\(CPUContext& ctx\)\{$', re.M)
DECL = re.compile(r'(?:uint32_t|double) (gpr|fpr|ps1)(\d+)=ctx\.\1\[\2\];')
STORE = re.compile(r'ctx\.(gpr|fpr|ps1)\[(\d+)\]=(?:gpr|fpr|ps1)\d+;')
CTX_BIT = re.compile(r'ctx\.(?:gpr\[(\d+)\]|ctr\b|inst_count\b|xer\b|fpr\[(\d+)\]|ps1\[(\d+)\]|cr\[(\d)\]\.(lt|gt|eq|so))')


def bit_of(text, offset):
    """Bit number (promote_regs numbering) of the ctx field starting at `offset`, or None."""
    m = CTX_BIT.match(text, offset)
    if not m:
        return None
    if m.group(1) is not None:
        return int(m.group(1))
    if m.group(2) is not None:
        return P.BIT_FPR + int(m.group(2))
    if m.group(3) is not None:
        return P.BIT_PS1 + int(m.group(3))
    if m.group(4) is not None:
        return P.BIT_CR + int(m.group(4)) * 4 + P.CR_BITS[m.group(5)]
    field = text[offset + 4:m.end()]
    return {'ctr': P.BIT_CTR, 'inst_count': P.BIT_IC, 'xer': P.BIT_XER}[field.split('.')[-1].strip('0123456789[]')]


def helper_effects(overlay_root):
    """(function, address) -> (reads, writes) bit sets, parsed from the generated helper text."""
    effects = {}
    for path in sorted(overlay_root.glob('*.h')):
        text = path.read_text(errors='surrogateescape')
        heads = list(HELPER_HEAD.finditer(text))
        for index, head in enumerate(heads):
            end = heads[index + 1].start() if index + 1 < len(heads) else len(text)
            body = text[head.end():end]
            reads = writes = 0
            for bank, index_ in DECL.findall(body):
                bit = int(index_) if bank == 'gpr' else (P.BIT_FPR + int(index_) if bank == 'fpr' else P.BIT_PS1 + int(index_))
                reads |= 1 << bit
            for bank, index_ in STORE.findall(body):
                bit = int(index_) if bank == 'gpr' else (P.BIT_FPR + int(index_) if bank == 'fpr' else P.BIT_PS1 + int(index_))
                writes |= 1 << bit
            if 'ctx.inst_count' in body:
                reads |= 1 << P.BIT_IC
                writes |= 1 << P.BIT_IC
            assert reads and writes, head.group(1)
            effects[(head.group(2), head.group(3))] = (reads, writes)
    return effects


def transfers(text, pattern):
    """[(count, bit)] for every ctx register transfer `pattern` finds in `text`."""
    out = []
    for found in pattern.finditer(text):
        offset = found.group(0).index('ctx.') + 4
        out.append((found.group(0), bit_of(found.group(0), offset)))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', type=Path, default=PORT)
    ap.add_argument('--limit', type=int, default=0, help='only the first N hot functions')
    ap.add_argument('--top', type=int, default=20)
    args = ap.parse_args()
    root = args.root.resolve()
    effects = helper_effects(root / 'runtime-overlays/bounded-blocks')
    texts, stats = C.promoted_texts(root, args.limit)
    totals = dict(sites=0, functions=0, unelided_spill=0, unelided_reload=0, elided_spill=0,
                  elided_reload=0, unknown_sites=0)
    per_function = []
    for name, file, promoted in texts:
        sites = unelided = elided = [0, 0, 0, 0]
        count = 0
        for line in promoted.split('\n'):
            m = BLOCKCALL.match(line)
            if not m:
                continue
            key = (m.group('function'), m.group('address'))
            if key not in effects:
                totals['unknown_sites'] += 1
                continue
            reads, writes = effects[key]
            spill = transfers(m.group('body'), C.SPILL)
            reload_ = transfers(m.group('tail'), C.RELOAD)
            count += 1
            unelided[0] += len(spill)
            unelided[1] += len(reload_)
            elided[0] += sum(1 for _, bit in spill if bit is not None and (reads >> bit) & 1)
            elided[1] += sum(1 for _, bit in reload_ if bit is not None and (writes >> bit) & 1)
        if count:
            totals['functions'] += 1
            totals['sites'] += count
            totals['unelided_spill'] += unelided[0]
            totals['unelided_reload'] += unelided[1]
            totals['elided_spill'] += elided[0]
            totals['elided_reload'] += elided[1]
            per_function.append(dict(function=name, file=file, sites=count,
                                     spill_now=unelided[0], spill_elided=elided[0],
                                     reload_now=unelided[1], reload_elided=elided[1]))
    per_function.sort(key=lambda r: -(r['spill_now'] - r['spill_elided']))
    report = dict(schema=1, helpers=len(effects), promote_stats=stats, totals=totals,
                  worst_by_saving=per_function[:args.top])
    out = root / 'reports/blockcall-effects.json'
    out.write_text(json.dumps(report, indent=2) + '\n')
    print('Bounded-block site cost: %d sites in %d hot functions (%d helpers known, %d sites unknown)' %
          (totals['sites'], totals['functions'], len(effects), totals['unknown_sites']))
    if totals['sites']:
        print('  emitted  spill %d (%.1f/site)  reload %d (%.1f/site)' %
              (totals['unelided_spill'], totals['unelided_spill'] / totals['sites'],
               totals['unelided_reload'], totals['unelided_reload'] / totals['sites']))
        print('  elided   spill %d (%.1f/site)  reload %d (%.1f/site)' %
              (totals['elided_spill'], totals['elided_spill'] / totals['sites'],
               totals['elided_reload'], totals['elided_reload'] / totals['sites']))
        print('  removable %d spill + %d reload transfers (%.0f%% of the emitted transfers)' %
              (totals['unelided_spill'] - totals['elided_spill'],
               totals['unelided_reload'] - totals['elided_reload'],
               100.0 * ((totals['unelided_spill'] - totals['elided_spill']) +
                        (totals['unelided_reload'] - totals['elided_reload'])) /
               max(1, totals['unelided_spill'] + totals['unelided_reload'])))
        for row in per_function[:8]:
            print('  %s %-14s sites=%-4d spill %d->%d  reload %d->%d' %
                  (row['file'], row['function'], row['sites'], row['spill_now'], row['spill_elided'],
                   row['reload_now'], row['reload_elided']))
    print('Report: %s' % out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
