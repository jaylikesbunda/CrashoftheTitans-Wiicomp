"""NATIVE_DIRECT_TEXCOORD_LOADER_V1 -- choose every reader of the generic vertex decode at compile time for direct F32 elements.

The generic decode (NativePackedGeneric<false>) reads each attribute through NativeVectorPlan::reader, a function pointer picked
once per draw. Its Direct flag means "position and normal are direct F32 with 3 components and the texcoord is direct F32 with 2",
so it hard-codes Read<1,4,2> for texcoords. A draw with a direct F32 position, a normal that is absent or direct F32, and a
texcoord that is absent, direct or indexed with any type or element count therefore stays on the indirect texcoord read. F3
shows that is the whole remaining fallback set: 10 draws/frame, all pos_direct, all failing texcoord_mask_mismatch, every other
gate zero.

NativeVectorPlan::Read<Mask,Type,Components> is the exact reader the plan would return (same width, same scale, same index
resolution) for every (mask, type, components) combination, so selecting it at compile time changes nothing but the call.

What this stage changes (fifo_parser.cpp only):
  1. NativePackedGeneric gains TexMask/TexType/TexElements template parameters (defaults -1/4/2, so every existing instantiation
     is the same code). The texcoord read becomes Read<TexMask,TexType,TexElements> when TexMask>=0, Read<1,4,2> under Direct
     and the plan reader otherwise.
  2. A generated NativePackedDirectLayout() maps the draw's texcoord VAT (mask none/direct/index8/index16 x type x elements) to
     the matching NativePackedGeneric<true,...> instantiation.
  3. NativePackedGenericPosition gains one arm before the indexed one: direct F32 3-component position, absent or direct F32
     3-component normal (no NBT), and at most one texcoord set. It routes through NativePackedDirectLayout().
Every instantiation uses the readers the generic path would reach through its plan pointer, so decoded vertices are unchanged.
NWII_NO_GENERIC_POSITION_LOADER=1 keeps the whole position-loader family, this arm included, on the original reader.

Runs after fix_generic_position_loader.py and fix_gx_architecture_metrics.py (its anchors are their text). Restore this stage
before the generic position loader. Byte oracle: tools/check_format_loaders.py (it calls NativePackedGenericPosition, so this arm
is covered). Idempotent; every edit keeps its original text base64-encoded.
"""
from pathlib import Path
import argparse, base64, re

MARK = 'NATIVE_DIRECT_TEXCOORD_LOADER_V1'
BLOCK = re.compile(r'/\* '+MARK+r' ([A-Za-z0-9+/=]+) \*/\n.*?/\* END_'+MARK+r' \*/', re.S)

# Texcoord VAT combinations the layout switch resolves, in the order they are emitted: mask, type, elements.
MASKS = ((0, 'None'), (1, 'Direct'), (2, 'Index8'), (3, 'Index16'))


def inst(mask, type_, elements):
    return 'NativePackedGeneric<true,-1,3,%d,%d,%d>(c,output,indices,inputs,words,defaults)' % (mask, type_, elements)


def layout_function():
    """The per-draw switch: (texMask, texType, texElements) -> a fully specialised NativePackedGeneric<true,...>."""
    out = ['static bool NativePackedDirectLayout(GXCommand& c,NativePackedBuffer& output,std::vector<uint32_t>& indices,',
           '                                   unsigned inputs,unsigned words,const float* defaults){',
           ' // Generated by tools/fix_direct_texcoord_loader.py: one arm per texcoord layout the census allows.',
           ' const auto& v=c.raw->vat;',
           ' const unsigned mask=unsigned(v.texMask[0]),type=unsigned(v.texType[0]);',
           ' const bool two=v.texElements[0]!=0;',
           ' if(mask==0)return %s;' % inst(0, 4, 2),
           ' if(mask==1){if(two)return %s;return %s;}' % (inst(1, 4, 2), inst(1, 4, 1)),
           ' if(mask==2||mask==3){']
    for mask in (2, 3):
        for elements in (2, 1):
            out.append('  if(mask==%d%s){switch(type){' % (mask, '&&two' if elements == 2 else '&&!two'))
            for type_ in range(5):
                out.append('   case %d:return %s;' % (type_, inst(mask, type_, elements)))
            out[-1] += '}}'
    out.append(' }')
    out.append(' return NativePackedGeneric<false>(c,output,indices,inputs,words,defaults);')
    out.append('}')
    return '\n'.join(out) + '\n'


def restore(s):
    s = BLOCK.sub(lambda m: base64.b64decode(m[1]).decode(), s)
    if MARK in s: raise ValueError('Incomplete direct texcoord metadata')
    return s


def replace(s, old, new):
    if s.count(old) != 1: raise ValueError(('Direct texcoord anchor', old[:90], s.count(old)))
    return s.replace(old, '/* '+MARK+' '+base64.b64encode(old.encode()).decode()+' */\n'+new+'/* END_'+MARK+' */')


def apply(s):
    s = restore(s)
    old = 'template<bool Direct,int PosMask=-1,int PosElements=3> static bool NativePackedGeneric('
    s = replace(s, old, 'template<bool Direct,int PosMask=-1,int PosElements=3,int TexMask=-1,int TexType=4,int TexElements=2> static bool NativePackedGeneric(')
    old = '            if (!(Direct ? NativeVectorPlan::Read<1,4,2>(tex[t],buf,off,buf_size,vtx.tex[t]) : tex[t].read(buf,off,buf_size,vtx.tex[t]))) {return false;}'
    new = '''            if (!([&](){
                if constexpr(TexMask>=0)return NativeVectorPlan::Read<TexMask,TexType,TexElements>(tex[t],buf,off,buf_size,vtx.tex[t]);
                else if constexpr(Direct)return NativeVectorPlan::Read<1,4,2>(tex[t],buf,off,buf_size,vtx.tex[t]);
                else return tex[t].read(buf,off,buf_size,vtx.tex[t]);
            }())) {return false;}'''
    s = replace(s, old, new)
    # The layout switch is defined after NativePackedGeneric and before the position loader that calls it.
    anchor = '// Select only qualified F32 position readers.'
    s = replace(s, anchor, layout_function() + anchor)
    anchor = ' if(enabled && c.raw->count>=32 && v.posType==VtxAttrType::F32 && (v.posMask==VtxAttrMask::Index8 || v.posMask==VtxAttrMask::Index16)){'
    arm = ''' if(enabled){
  // NATIVE_DIRECT_TEXCOORD_LOADER_V1: direct F32 position with an absent or direct F32 normal (3 components, no NBT) and at
  // most one texcoord set. Every reader is the one the generic path would reach through its plan pointer.
  bool tex0_only=true;for(unsigned t=1;t<8;++t)tex0_only=tex0_only && v.texMask[t]==VtxAttrMask::None;
  if(v.posMask==VtxAttrMask::Direct && v.posType==VtxAttrType::F32 && v.posElements &&
     (v.nrmMask==VtxAttrMask::None || (v.nrmMask==VtxAttrMask::Direct && v.nrmType==VtxAttrType::F32 && !v.nrmElements)) &&
     tex0_only){
   native_gx_work::Add(native_gx_work::GenericPositionSpecialized);
   return NativePackedDirectLayout(c,output,indices,inputs,words,defaults);
  }
 }
'''
    s = replace(s, anchor, arm + anchor)
    return s

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--port',type=Path,default=Path(__file__).resolve().parents[1]);ap.add_argument('--restore',action='store_true');args=ap.parse_args()
    path=args.port/'build/nwii-full-source/nWiiRuntime/src/hle/gx/fifo_parser.cpp'
    old=path.read_text();new=restore(old) if args.restore else apply(old)
    if old!=new:path.write_text(new)
    print('Direct texcoord loader '+('restored' if args.restore else 'staged'))
if __name__=='__main__':main()
