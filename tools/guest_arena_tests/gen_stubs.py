"""Write a stub for every guest function a hot unit calls but does not define (extern "C" func_XXXXXXXX)."""
import re, sys

unit, out = sys.argv[1], sys.argv[2]
text = open(unit, errors='replace').read()
defined = set(re.findall(r'(?m)^(?:static )?(?:__attribute__\(\([^\n]*?\)\) )?(?:NWII_GUEST_ABI )?(?:__attribute__\(\([^\n]*?\)\) )?void (func_[0-9A-F]{8})\(', text))
used = set(re.findall(r'\b(func_[0-9A-F]{8})\b', text))
missing = sorted(used - defined)
with open(out, 'w') as f:
    f.write('// generated by gen_stubs.py: callees outside the unit\n')
    for name in missing:
        f.write('extern "C" NWII_GUEST_ABI void %s(CPUContext& ctx) { stub_callee(ctx, 0x%s); }\n' % (name, name[5:]))
print('%d stubs, %d defined in unit' % (len(missing), len(defined)))
